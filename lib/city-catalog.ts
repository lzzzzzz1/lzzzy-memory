const normalize = (value: string) => value.trim().toLowerCase().replace(/[\s·._-]+/g, " ").replace(/市$/, "");

export function findCity(country: string, city: string) {
  const normalizedCountry = normalize(country);
  const normalizedCity = normalize(city);
  return cities.find((entry) => entry.country.some((name) => normalize(name) === normalizedCountry) && entry.city.some((name) => normalize(name) === normalizedCity));
}
